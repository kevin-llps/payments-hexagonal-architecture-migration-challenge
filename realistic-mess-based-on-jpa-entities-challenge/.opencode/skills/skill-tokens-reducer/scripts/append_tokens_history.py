#!/usr/bin/env python3
"""Append one measured run to TOKENS_HISTORY.md and refresh the histogram.

Rows are append-only: an existing session ID is never added twice, and no
existing row is edited. The derived histogram block is regenerated by
render_tokens_histogram.py.

Usage:
    append_tokens_history.py --history <path> --run-json <path> [--target <id>]

Exit codes: 0 = appended or already present, 1 = invalid input, 2 = usage error.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render_tokens_histogram as histogram  # noqa: E402


class AppendError(RuntimeError):
    """Raised when a run cannot be appended safely."""


def format_cell(value: Any) -> str:
    text = "" if value is None else str(value)
    text = " ".join(text.replace("|", "\\|").split())
    return text


def token_total(run: dict[str, Any]) -> int:
    tokens = run.get("tokens") or {}
    if "total" in tokens:
        return int(tokens["total"])
    cache = tokens.get("cache") or {}
    return sum(
        int(tokens.get(key) or 0)
        for key in ("input", "output", "reasoning")
    ) + int(cache.get("read") or 0) + int(cache.get("write") or 0)


def required(run: dict[str, Any], key: str) -> Any:
    value = run.get(key)
    if value is None or value == "":
        raise AppendError(f"run JSON is missing required field: {key}")
    return value


def history_row(run: dict[str, Any]) -> str:
    tokens = run.get("tokens") or {}
    cache = tokens.get("cache") or {}
    model = run.get("model")
    if isinstance(model, dict):
        provider = model.get("providerID") or model.get("provider") or ""
        name = model.get("id") or model.get("modelID") or ""
        label = f"{provider}/{name}" if provider else str(name)
        model = f"{label} / {run.get('agent') or ''}"
    else:
        model = f"{model} / {run.get('agent') or ''}" if model else run.get("agent") or ""
    values = [
        format_cell(required(run, "date")),
        f"`{format_cell(required(run, 'session_id'))}`",
        format_cell(run.get("children", 0)),
        format_cell(required(run, "phase")),
        format_cell(required(run, "scenario")),
        format_cell(required(run, "run")),
        format_cell(run.get("title", "")),
        format_cell(run.get("reason", "")),
        format_cell(model),
        format_cell(tokens.get("input", 0)),
        format_cell(tokens.get("output", 0)),
        format_cell(tokens.get("reasoning", 0)),
        format_cell(cache.get("read", 0)),
        format_cell(cache.get("write", 0)),
        format_cell(token_total(run)),
        format_cell(required(run, "result")),
    ]
    return "| " + " | ".join(values) + " |"


def append_run(history: Path, run: dict[str, Any], target: str | None = None) -> bool:
    if not history.is_file():
        if not target:
            raise AppendError(f"history not found: {history}")
        history.parent.mkdir(parents=True, exist_ok=True)
        history.write_text(histogram.new_history(target), encoding="utf-8")
    text = history.read_text(encoding="utf-8")
    existing = {row["session_id"] for row in histogram.parse_runs(text)}
    if run.get("session_id") in existing:
        histogram.rewrite_history(history)
        return False
    lines = text.splitlines()
    _, _, insert_at = histogram.find_runs_table(lines)
    lines.insert(insert_at, history_row(run))
    history.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    histogram.rewrite_history(history)
    return True


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--history", required=True)
    parser.add_argument("--run-json", required=True)
    parser.add_argument("--target", help="target skill ID, needed when history is absent")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    history = Path(args.history).expanduser()
    run_path = Path(args.run_json).expanduser()
    try:
        run = json.loads(run_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        print(f"error: cannot read run JSON: {error}", file=sys.stderr)
        return 1
    try:
        appended = append_run(history, run, args.target)
    except (AppendError, histogram.HistoryError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    action = "appended" if appended else "already present"
    print(f"{action}: {run.get('session_id')} -> {history}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
